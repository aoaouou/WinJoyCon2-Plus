using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Net;
using System.Net.Sockets;
using System.Reflection;
using System.Text;
using System.Threading;
using System.Threading.Tasks;

/// <summary>
/// HIDMaestro bridge for Joy-Con 2.
///
/// Runs as a long-lived process. Speaks a tiny line protocol over TCP so the
/// Python host can drive two native Joy-Con 2 devices and receive HD-rumble
/// output reports.
///
/// Protocol (UTF-8, newline terminated), TCP 127.0.0.1:3250:
///   HELLO\n                       -> OK &lt;version&gt;\n
///   INIT\n                        -> OK\n (creates L + R controllers once)
///   STATE &lt;side&gt; &lt;buttons:uint&gt; &lt;lx:int&gt; &lt;ly:int&gt; &lt;rx:int&gt; &lt;ry:int&gt;\n
///                                -> OK\n  (side = L | R)
///   IMU &lt;side&gt; &lt;ax:float&gt; &lt;ay&gt; &lt;az&gt; &lt;gx&gt; &lt;gy&gt; &lt;gz&gt;\n -> OK\n
///   PING\n                        -> PONG\n
///   QUIT\n                        -> BYE\n (shutdown)
///
/// On connection the server immediately starts forwarding output reports:
///   OUT &lt;side&gt; &lt;leftMotor:float&gt; &lt;rightMotor:float&gt;\n
/// for each decoded rumble, and
///   RAW &lt;side&gt; &lt;hex&gt;\n
/// for raw output reports (fallback). The Python side subscribes once.
///
/// Authoritative sources for the device identity / reports are in the project:
///   sessions/2026-11-12_.../ref/switch2_research/ (descriptors.md, hid_reports.md)
///   profiles generated by make_hidmaestro_profiles.py
/// </summary>
internal static class Program
{
    const int Port = 3250;
    static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    static Assembly _asm = null!;
    static Type _ctxType = null!;
    static Type _backendType = null!;
    static Type _stateType = null!;
    static Type _btnType = null!;
    static Type _axisType = null!;
    static Type _profileType = null!;
    static Type _axesDictType = null!;
    static object _ctx = null!;
    static MethodInfo _getProfile = null!;
    static MethodInfo _createController = null!;

    sealed class Device
    {
        public string Side = "";
        public object Ctrl = null!;
        public MethodInfo Submit = null!;
        public object State = null!;
        public System.Collections.IDictionary Axes = null!;
        // The profile's stick axes (HMAxis), so we can write the right
        // HMAxis for the half this device represents.
        public object LeftXAxis = null!;
        public object LeftYAxis = null!;
        public object RightXAxis = null!;
        public object RightYAxis = null!;
        public uint Buttons;
        public readonly object Lock = new();
        // last rumble values, forwarded to subscribers
        public float LeftMotor, RightMotor;
        public long RumbleSeq;
    }

    static readonly Dictionary<string, Device> Devices = new();
    static readonly object _devicesLock = new();
    static readonly List<StreamWriter> _subscribers = new();
    static readonly object _subLock = new();
    static string _profilesDir = "";

    static int Main(string[] args)
    {
        // args[0] = profiles directory
        // args[1] = optional port override（兼容旧调用：若非数字则忽略）
        _profilesDir = args.Length > 0 ? args[0] : AppContext.BaseDirectory;
        int portArg = args.Length > 1 && int.TryParse(args[1], out _) ? 1 : 2;
        int port = args.Length > portArg && int.TryParse(args[portArg], out var p) ? p : Port;

        string dll = Path.Combine(AppContext.BaseDirectory, "HIDMaestro.Core.dll");
        if (!File.Exists(dll))
        {
            Console.Error.WriteLine("HIDMaestro.Core.dll missing at " + dll);
            return 2;
        }
        _asm = Assembly.LoadFrom(dll);
        _ctxType = _asm.GetType("HIDMaestro.HMContext")!;
        _backendType = _asm.GetType("HIDMaestro.HMBackend")!;
        _stateType = _asm.GetType("HIDMaestro.HMGamepadState")!;
        _btnType = _asm.GetType("HIDMaestro.HMButton")!;
        _axisType = _asm.GetType("HIDMaestro.HMAxis")!;
        _profileType = _asm.GetType("HIDMaestro.HMProfile")!;
        _axesDictType = typeof(Dictionary<,>).MakeGenericType(_axisType, typeof(float));
        _getProfile = _ctxType.GetMethod("GetProfile")!;
        _createController = _ctxType.GetMethod("CreateController",
            new[] { _profileType, typeof(string), _backendType })!;

        var listener = new TcpListener(IPAddress.Loopback, port);
        listener.Start();
        Console.WriteLine($"HmBridge listening on 127.0.0.1:{port}");

        // Accept loop; each client gets its own task.
        while (true)
        {
            TcpClient client;
            try { client = listener.AcceptTcpClient(); }
            catch (SocketException) { break; }
            catch (ObjectDisposedException) { break; }
            _ = Task.Run(() => HandleClient(client));
        }
        return 0;
    }

    static void HandleClient(TcpClient client)
    {
        client.NoDelay = true;
        using (client)
        using (var ns = client.GetStream())
        using (var reader = new StreamReader(ns, new UTF8Encoding(false)))
        using (var writer = new StreamWriter(ns, new UTF8Encoding(false)) { AutoFlush = true })
        {
            try
            {
                string? line;
                while ((line = reader.ReadLine()) != null)
                {
                    var parts = line.Split(' ');
                    if (parts.Length == 0) continue;
                    var cmd = parts[0].Trim().ToUpperInvariant();
                    switch (cmd)
                    {
                        case "HELLO":
                            writer.WriteLine("OK 2.3.0-hmbridge");
                            break;
                        case "INIT":
                            lock (_devicesLock)
                            {
                                if (Devices.Count == 0)
                                {
                                    try { InitControllers(); writer.WriteLine("OK"); }
                                    catch (Exception ex)
                                    { writer.WriteLine("ERR " + Safe(ex)); }
                                }
                                else writer.WriteLine("OK");
                            }
                            // subscribe this writer for rumble events
                            lock (_subLock) if (!_subscribers.Contains(writer)) _subscribers.Add(writer);
                            break;
                        case "SUB":
                            lock (_subLock) if (!_subscribers.Contains(writer)) _subscribers.Add(writer);
                            writer.WriteLine("OK");
                            break;
                        case "STATE":
                            if (parts.Length < 7) { writer.WriteLine("ERR bad STATE"); break; }
                            try
                            {
                                var side = parts[1].Trim().ToUpperInvariant();
                                var buttons = uint.Parse(parts[2], Inv);
                                int lx = int.Parse(parts[3], Inv), ly = int.Parse(parts[4], Inv),
                                    rx = int.Parse(parts[5], Inv), ry = int.Parse(parts[6], Inv);
                                // 可选第 7 参数：十字键角度（0=N,90=E,180=S,270=W,
                                // 45/135/225/315=对角；-1=无方向）。真机握把
                                // profile 的 DPAD_* 是 sentinel，只能经 Hat 写入，
                                // buttons 掩码写不进去（VendorBlobCodec.cs:1112-1137）。
                                float? hat = null;
                                if (parts.Length >= 8)
                                {
                                    float h = float.Parse(parts[7], Inv);
                                    if (h >= 0) hat = h;
                                }
                                SetState(side, buttons, lx, ly, rx, ry, hat);
                                writer.WriteLine("OK");
                            }
                            catch (Exception ex) { writer.WriteLine("ERR " + Safe(ex)); }
                            break;
                        case "IMU":
                            if (parts.Length < 8) { writer.WriteLine("ERR bad IMU"); break; }
                            try
                            {
                                var side = parts[1].Trim().ToUpperInvariant();
                                float ax = float.Parse(parts[2], Inv), ay = float.Parse(parts[3], Inv),
                                      az = float.Parse(parts[4], Inv), gx = float.Parse(parts[5], Inv),
                                      gy = float.Parse(parts[6], Inv), gz = float.Parse(parts[7], Inv);
                                SetImu(side, ax, ay, az, gx, gy, gz);
                                writer.WriteLine("OK");
                            }
                            catch (Exception ex) { writer.WriteLine("ERR " + Safe(ex)); }
                            break;
                        case "PING":
                            writer.WriteLine("PONG");
                            break;
                        case "QUIT":
                            writer.WriteLine("BYE");
                            Environment.Exit(0);
                            break;
                        default:
                            writer.WriteLine("ERR unknown " + cmd);
                            break;
                    }
                }
            }
            catch (IOException) { }
            catch (Exception ex) { Console.Error.WriteLine("client: " + Safe(ex)); }
            finally
            {
                lock (_subLock) _subscribers.Remove(writer);
            }
        }
    }

    static string Safe(Exception ex) => (ex.InnerException ?? ex).Message.Replace('\n', ' ');

    static void InitControllers()
    {
        // Usbip backend: registers a real HID device interface that hidapi/SetupAPI
        // can enumerate. UMDF2 backend creates a HIDClass node but does NOT register
        // the HID device interface class, so SDL/hidapi never sees it (verified:
        // SetupAPI enumerated 25 HID interfaces, 0 from the UMDF2 controller).
        _ctx = Activator.CreateInstance(_ctxType,
            new object[] { Enum.Parse(_backendType, "Usbip") })!;

        int n = _profilesDir.Length > 0
            ? (int)_ctxType.GetMethod("LoadProfilesFromDirectory")!.Invoke(_ctx, new object[] { _profilesDir })!
            : (int)_ctxType.GetMethod("LoadDefaultProfiles")!.Invoke(_ctx, null)!;
        Console.WriteLine($"loaded profiles: {n}");

        var issues = (System.Collections.IEnumerable)_ctxType.GetProperty("ProfileLoadIssues")!.GetValue(_ctx)!;
        foreach (var i in issues.Cast<object>()) Console.Error.WriteLine("profile issue: " + i);

        // 唯一的输出形态：独立 Joy-Con 1（PID 2006/2007，真机 HID 描述符）。
        // 平台自动把左右两只组合成一对，全平台兼容；按键/HD震动/陀螺仪
        // 走 profile 的 0x30/0x3F 报告，与旧 USB/IP 方案功能一致。
        var profilePair = new[] { ("L", "joycon-l"), ("R", "joycon-r") };
        foreach (var (side, profileId) in profilePair)
        {
            var prof = _getProfile.Invoke(_ctx, new object[] { profileId });
            if (prof == null) throw new Exception("profile missing: " + profileId);

            string key = "jc1-" + side + "-" + Guid.NewGuid().ToString("N").Substring(0, 8);
            var ctrl = _createController.Invoke(_ctx,
                new object[] { prof, key, Enum.Parse(_backendType, "Usbip") })!;

            var dev = new Device
            {
                Side = side,
                Ctrl = ctrl,
                Submit = ctrl.GetType().GetMethod("SubmitState")!,
                Axes = (System.Collections.IDictionary)Activator.CreateInstance(_axesDictType)!,
            };

            // Which HMAxis carries this half's stick. The profile's Sticks
            // come from the HID descriptor, not from the JSON layout: the
            // real charging-grip descriptor is the Switch 1 Pro one, so it
            // declares X/Y (left stick) and Rx/Rz (right stick). The left
            // half writes X/Y, the right half writes Rx/Rz.
            var sticks = (System.Collections.IEnumerable)_profileType.GetProperty("Sticks")!.GetValue(prof)!;
            var stickList = sticks.Cast<object>().ToList();
            void AxisOf(object stick, string prop, ref object slot)
            {
                slot = stick.GetType().GetProperty(prop)!.GetValue(stick)!;
            }
            if (stickList.Count >= 1)
            {
                if (side == "L")
                {
                    AxisOf(stickList[0], "XAxis", ref dev.LeftXAxis);
                    AxisOf(stickList[0], "YAxis", ref dev.LeftYAxis);
                }
                else
                {
                    // The right half's own stick is the second one when the
                    // descriptor declares both; fall back to the first.
                    var s = stickList.Count >= 2 ? stickList[1] : stickList[0];
                    AxisOf(s, "XAxis", ref dev.RightXAxis);
                    AxisOf(s, "YAxis", ref dev.RightYAxis);
                }
            }
            if (dev.LeftXAxis == null) { dev.LeftXAxis = Enum.Parse(_axisType, "X"); dev.LeftYAxis = Enum.Parse(_axisType, "Y"); }
            if (dev.RightXAxis == null) { dev.RightXAxis = Enum.Parse(_axisType, "Rx"); dev.RightYAxis = Enum.Parse(_axisType, "Rz"); }

            // neutral axes; Y inverted so SDK 0.5 == wire center
            dev.Axes.Add(dev.LeftXAxis, 0.5f);
            dev.Axes.Add(dev.LeftYAxis, 0.5f);
            dev.Axes.Add(dev.RightXAxis, 0.5f);
            dev.Axes.Add(dev.RightYAxis, 0.5f);
            dev.State = Activator.CreateInstance(_stateType)!;
            _stateType.GetField("Axes")!.SetValue(dev.State, dev.Axes);
            _stateType.GetField("Buttons")!.SetValue(dev.State, Enum.ToObject(_btnType, 0u));

            // rumble output subscription
            HookOutput(dev, ctrl);

            lock (_devicesLock) Devices[side] = dev;
            Console.WriteLine($"created {profileId} as {side}");
        }
    }

    static void HookOutput(Device dev, object ctrl)
    {
        // OutputReceived = Action<HMController, HMOutputPacket>。
        // ★ 不能直接用 Delegate.CreateDelegate(ht, lambda.Method)：
        //   lambda 是 (object,object)，与 (HMController,HMOutputPacket) 参数
        //   类型不兼容，CreateDelegate 会抛异常并被 catch 吞掉 → 事件根本没
        //   挂上（这就是之前完全收不到震动的原因）。改用 Expression 构造
        //   签名完全匹配的委托。
        var ev = ctrl.GetType().GetEvent("OutputReceived");
        if (ev == null) return;
        try
        {
            var ht = ev.EventHandlerType!;
            var args = ht.GetGenericArguments();
            var packetType = args[1];  // HMOutputPacket
            var ridField = packetType.GetField("ReportId");
            var dataField = packetType.GetField("Data");
            var srcField = packetType.GetField("Source");
            if (ridField == null || dataField == null) return;

            var pCtrl = System.Linq.Expressions.Expression.Parameter(args[0], "c");
            var pPkt = System.Linq.Expressions.Expression.Parameter(packetType, "p");
            var sideField = typeof(HmBridgeSupport.OutputHook).GetField("Side")!;
            var handleMi = typeof(HmBridgeSupport.OutputHook).GetMethod("Handle")!;
            // (c, p) => { OutputHook.Side = dev.Side; OutputHook.Handle(c, (object)p); }
            var setSide = System.Linq.Expressions.Expression.Assign(
                System.Linq.Expressions.Expression.Field(null, sideField),
                System.Linq.Expressions.Expression.Constant(dev.Side));
            var callHandle = System.Linq.Expressions.Expression.Call(handleMi,
                System.Linq.Expressions.Expression.Convert(pCtrl, typeof(object)),
                System.Linq.Expressions.Expression.Convert(pPkt, typeof(object)));
            var body = System.Linq.Expressions.Expression.Block(setSide, callHandle);
            var lambda = System.Linq.Expressions.Expression.Lambda(ht, body, pCtrl, pPkt);
            ev.AddEventHandler(ctrl, lambda.Compile());
            // 发布回调：把振幅推给订阅者
            HmBridgeSupport.OutputHook.OnRumble = (side, amp) =>
                PublishRumble(GetDevice(side), amp, amp, "OUT");
            Console.WriteLine($"output hook attached: {dev.Side}");
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine("HookOutput failed: " + ex.Message);
        }
    }

    /// <summary>按侧别取设备（震动回调里用）。</summary>
    static Device GetDevice(string side)
    {
        lock (_devicesLock)
            return Devices.TryGetValue(side, out var d) ? d : throw new Exception("no device " + side);
    }

    static void PublishRumble(Device dev, float l, float r, string tag)
    {
        dev.LeftMotor = l; dev.RightMotor = r;
        dev.RumbleSeq++;
        string msg = $"OUT {dev.Side} {l.ToString("R", Inv)} {r.ToString("R", Inv)}";
        Broadcast(msg);
    }

    static void PublishRaw(Device dev, byte[] b)
    {
        string hex = Convert.ToHexString(b);
        Broadcast($"RAW {dev.Side} {hex}");
    }

    static void Broadcast(string msg)
    {
        StreamWriter[] arr;
        lock (_subLock) arr = _subscribers.ToArray();
        foreach (var w in arr)
        {
            try { w.WriteLine(msg); } catch { lock (_subLock) _subscribers.Remove(w); }
        }
    }

    static void SetState(string side, uint buttons, int lx, int ly, int rx, int ry, float? hat = null)
    {
        lock (_devicesLock)
        {
            if (!Devices.TryGetValue(side, out var dev)) throw new Exception("no device " + side);
            lock (dev.Lock)
            {
                dev.Buttons = buttons;
                _stateType.GetField("Buttons")!.SetValue(dev.State, Enum.ToObject(_btnType, buttons));
                // 十字键：DPAD_* 是编译期 sentinel，运行时由 Hat/HatDegrees 解析
                // （VendorBlobCodec.cs:1112-1137），buttons 掩码写不进去。
                _stateType.GetField("HatDegrees")!.SetValue(dev.State, hat.HasValue ? (object)hat.Value : null);
                var axes = dev.Axes;
                // Each half only carries its own stick: the left half writes
                // the left stick axes, the right half the right ones. The
                // other pair stays at center.
                if (dev.Side == "L")
                {
                    axes[dev.LeftXAxis] = Norm(lx);
                    axes[dev.LeftYAxis] = 1f - Norm(ly);
                }
                else
                {
                    axes[dev.RightXAxis] = Norm(rx);
                    axes[dev.RightYAxis] = 1f - Norm(ry);
                }
                dev.Submit.Invoke(dev.Ctrl, new object[] { dev.State });
            }
        }
    }

    static float Norm(int v)
    {
        // inputs are 12-bit Joy-Con stick values (0..4095)
        if (v < 0) v = 0; if (v > 4095) v = 4095;
        return v / 4095f;
    }

    static void SetImu(string side, float ax, float ay, float az, float gx, float gy, float gz)
    {
        lock (_devicesLock)
        {
            if (!Devices.TryGetValue(side, out var dev)) throw new Exception("no device " + side);
            lock (dev.Lock)
            {
                var st = dev.State;
                // Python 侧 imu_proc.imu() 输出真机 JC1 的 wire raw（已验证
                // 的量纲与轴向）。HIDMaestro profile 字段是语义 g/dps，写出时
                // 会再乘 scale（accel×4096、gyro×13371/936）。故先反算成
                // 语义值，profile scale 回去正好等于旧方案的 wire raw。
                const float aScale = 4096f;
                const float gScale = 13371f / 936f;
                _stateType.GetField("AccelGX")?.SetValue(st, ax / aScale);
                _stateType.GetField("AccelGY")?.SetValue(st, ay / aScale);
                _stateType.GetField("AccelGZ")?.SetValue(st, az / aScale);
                _stateType.GetField("GyroDpsX")?.SetValue(st, gx / gScale);
                _stateType.GetField("GyroDpsY")?.SetValue(st, gy / gScale);
                _stateType.GetField("GyroDpsZ")?.SetValue(st, gz / gScale);
                dev.Submit.Invoke(dev.Ctrl, new object[] { st });
            }
        }
    }
}
